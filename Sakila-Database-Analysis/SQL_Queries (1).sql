USE sakila;


-- ------------------------------------------------------------
-- Q1. First name, last name and rental date of all customers
--     who rented a film
-- ------------------------------------------------------------
SELECT c.first_name,
       c.last_name,
       r.rental_date
FROM customer c
JOIN rental r ON c.customer_id = r.customer_id;


-- ------------------------------------------------------------
-- Q2. First name, last name and address of customers whose
--     district is either Alberta or Texas
-- ------------------------------------------------------------
SELECT c.first_name,
       c.last_name,
       a.address
FROM customer c
JOIN address a ON c.address_id = a.address_id
WHERE a.district IN ('Alberta', 'Texas');


-- ------------------------------------------------------------
-- Q3. All films with their category names (including films with
--     no category), sorted by category name
-- ------------------------------------------------------------
SELECT f.title,
       c.name AS category_name
FROM film f
LEFT JOIN film_category fc ON f.film_id = fc.film_id
LEFT JOIN category c ON fc.category_id = c.category_id
ORDER BY category_name;


-- ------------------------------------------------------------
-- Q4. Number of rentals per store
-- ------------------------------------------------------------
SELECT s.store_id,
       COUNT(r.rental_id) AS total_rentals
FROM rental r
JOIN inventory i ON r.inventory_id = i.inventory_id
JOIN store s ON i.store_id = s.store_id
GROUP BY s.store_id;


-- ------------------------------------------------------------
-- Q5. Categories that have more than 50 films
-- ------------------------------------------------------------
SELECT c.name,
       COUNT(fc.film_id) AS total_films
FROM category c
JOIN film_category fc ON c.category_id = fc.category_id
GROUP BY c.name
HAVING COUNT(fc.film_id) > 50;


-- ------------------------------------------------------------
-- Q6. Film titles rented by the customer 'Mary Smith'
-- ------------------------------------------------------------
SELECT title
FROM film
WHERE film_id IN (
    SELECT i.film_id
    FROM inventory i
    JOIN rental r ON i.inventory_id = r.inventory_id
    WHERE r.customer_id IN (
        SELECT customer_id
        FROM customer
        WHERE first_name = 'Mary'
          AND last_name = 'Smith'
    )
);


-- ------------------------------------------------------------
-- Q7. Total rental income generated by each film
-- ------------------------------------------------------------
SELECT f.title,
       SUM(p.amount) AS total_income
FROM film f
JOIN inventory i ON f.film_id = i.film_id
JOIN rental r ON i.inventory_id = r.inventory_id
JOIN payment p ON r.rental_id = p.rental_id
GROUP BY f.film_id, f.title;


-- ------------------------------------------------------------
-- Q8. Total number of films each actor has acted in
-- ------------------------------------------------------------
SELECT a.first_name,
       a.last_name,
       COUNT(fa.film_id) AS total_films
FROM actor a
JOIN film_actor fa ON a.actor_id = fa.actor_id
GROUP BY a.actor_id, a.first_name, a.last_name;


-- ------------------------------------------------------------
-- Q9. All rentals with a CASE statement: 'New Customer' if
--     customer_id > 300, otherwise 'Regular Customer'
-- ------------------------------------------------------------
SELECT rental_id,
       customer_id,
       CASE
           WHEN customer_id > 300 THEN 'New Customer'
           ELSE 'Regular Customer'
       END AS customer_type
FROM rental;


-- ------------------------------------------------------------
-- Q10. Films whose title starts with 'A' (title and release year)
-- ------------------------------------------------------------
SELECT title,
       release_year
FROM film
WHERE title LIKE 'A%';


